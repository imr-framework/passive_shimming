def export_and_verify(
    mesh,
    path,
    label,
):
    path = Path(
        path
    )

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    if not mesh.is_watertight:
        raise RuntimeError(
            f"{label} is not watertight; refusing export."
        )

    if not mesh.is_volume:
        raise RuntimeError(
            f"{label} is not a valid volume; refusing export."
        )

    mesh.export(
        path
    )

    reloaded = trimesh.load(
        path,
        force="mesh",
    )

    print(
        f"\n{label}"
    )

    print(
        f"  STL: "
        f"{path}"
    )

    print(
        f"  watertight: "
        f"{reloaded.is_watertight}"
    )

    print(
        f"  volume: "
        f"{reloaded.is_volume}"
    )

    print(
        f"  extents [mm]: "
        f"{np.asarray(reloaded.extents)}"
    )

    if not reloaded.is_watertight:
        raise RuntimeError(
            f"Reloaded {label} STL is not watertight."
        )

    if not reloaded.is_volume:
        raise RuntimeError(
            f"Reloaded {label} STL is not a valid volume."
        )

    return path


