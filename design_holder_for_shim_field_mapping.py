def show_assembled(
    holder,
    center_finder,
    d: DerivedDimensions,
    holder_metadata,
):
    """
    Visualization of actual geometry plus proxy top/bottom shim trays.
    Proxy trays are visualization-only and are NOT exported.
    """

    scene = trimesh.Scene()

    holder_display = holder.copy()
    holder_display.visual.face_colors = (
        [180, 180, 205, 185]
    )

    scene.add_geometry(
        holder_display,
        node_name="holder",
    )

    bottom_tray = disc(
        diameter=
            d.tray_diameter,
        thickness=
            d.tray_thickness,
        center_z=
            holder_metadata[
                "bottom_tray_center_z"
            ],
    )

    top_tray = disc(
        diameter=
            d.tray_diameter,
        thickness=
            d.tray_thickness,
        center_z=
            holder_metadata[
                "top_tray_center_z"
            ],
    )

    bottom_tray.visual.face_colors = (
        [95, 175, 230, 150]
    )

    top_tray.visual.face_colors = (
        [95, 175, 230, 150]
    )

    scene.add_geometry(
        bottom_tray,
        node_name=
            "bottom_shim_tray_proxy",
    )

    scene.add_geometry(
        top_tray,
        node_name=
            "top_shim_tray_proxy",
    )

    finder_display = center_finder.copy()

    finder_display.apply_translation(
        [
            0.0,
            0.0,
            holder_metadata[
                "bottom_support_surface_z"
            ],
        ]
    )

    finder_display.visual.face_colors = (
        [230, 175, 90, 245]
    )

    scene.add_geometry(
        finder_display,
        node_name=
            "center_finder_installed",
    )

    origin = trimesh.creation.icosphere(
        subdivisions=2,
        radius=max(
            0.15 * d.tray_thickness,
            0.8,
        ),
    )

    origin.visual.face_colors = (
        [40, 230, 40, 255]
    )

    scene.add_geometry(
        origin,
        node_name=
            "origin_0_0_0",
    )

    scene.show()


