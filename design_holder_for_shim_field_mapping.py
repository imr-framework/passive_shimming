def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Design a passive-shim field-mapping holder from only the shim "
            "tray diameter, tray thickness, and tray center separation."
        )
    )

    parser.add_argument(
        "--tray-diameter",
        type=float,
        default=
            DEFAULT_TRAY_DIAMETER_MM,
        help=(
            "Shim-tray diameter in mm. "
            f"Default: {DEFAULT_TRAY_DIAMETER_MM:g}."
        ),
    )

    parser.add_argument(
        "--tray-thickness",
        type=float,
        default=
            DEFAULT_TRAY_THICKNESS_MM,
        help=(
            "Shim-tray physical thickness in mm. "
            f"Default: {DEFAULT_TRAY_THICKNESS_MM:g}."
        ),
    )

    parser.add_argument(
        "--separation",
        type=float,
        default=
            DEFAULT_SEPARATION_MM,
        help=(
            "CENTER-TO-CENTER separation of the two shim trays in mm. "
            f"Default: {DEFAULT_SEPARATION_MM:g}."
        ),
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=
            Path(
                "./shim_field_mapping_holder_output"
            ),
    )

    parser.add_argument(
        "--no-show",
        action=
            "store_true",
        help=(
            "Generate/export without opening Trimesh viewers."
        ),
    )

    return parser.parse_args()


# ============================================================================
# MAIN
# ============================================================================

def main():
    args = parse_args()

    d = derive_dimensions(
        tray_diameter_mm=
            args.tray_diameter,
        tray_thickness_mm=
            args.tray_thickness,
        separation_mm=
            args.separation,
    )

    holder, holder_metadata = build_holder(
        d
    )

    center_finder, center_metadata = (
        build_center_finder(
            d
        )
    )

    print_design_report(
        d,
        holder_metadata,
        center_metadata,
    )

    output_dir = Path(
        args.output_dir
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    holder_path = export_and_verify(
        holder,
        output_dir
        / "shim_field_mapping_holder.stl",
        "Shim field-mapping holder",
    )

    center_path = export_and_verify(
        center_finder,
        output_dir
        / "shim_field_mapping_center_finder.stl",
        "Registered center finder",
    )

    if not args.no_show:
        show_holder(
            holder
        )

        show_center_finder(
            center_finder
        )

        show_assembled(
            holder=
                holder,
            center_finder=
                center_finder,
            d=
                d,
            holder_metadata=
                holder_metadata,
        )

    return {
        "derived_dimensions":
            d,

        "holder":
            holder,

        "center_finder":
            center_finder,

        "holder_metadata":
            holder_metadata,

        "center_metadata":
            center_metadata,

        "holder_stl":
            holder_path,

        "center_finder_stl":
            center_path,
    }


if __name__ == "__main__":
    main()
